// Import the prototype's action tables into Rust.
//
// Reads docs/prototype/Main.dc.html, takes its ACT, MENUBAR, DOCK, IC and
// BEHAVIOURS tables as they are, applies the Rust-side changes listed below,
// and writes crates/prism-app/src/actions/table.rs. Run it again whenever the
// prototype's tables change:
//
//     node scripts/import_prototype.js
//
// Nothing else is read from the prototype, and its code is not run: the
// tables are plain data, evaluated on their own.
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'docs/prototype/Main.dc.html'), 'utf8');

// Cut the data block: from the ACT table to the end of the IC table.
const start = html.indexOf('const ACT = {};');
const end = html.indexOf('const esc =', start);
if (start < 0 || end < 0) throw new Error('could not find the action tables');
const block = html.slice(start, end);
const data = new Function(block + '\nreturn { ACT, MENUBAR, DOCK, IC, BEHAVIOURS };')();

// ---- Rust-side changes (brief 03, "Pick up the prototype's buttons and menus") ----
// 1. The demo scene is a prototype-only helper: not ported.
delete data.ACT['help.smartdemo'];
// 2. Actions from the plan that the prototype does not have yet.
const add = (id, name, key) => { data.ACT[id] = { id, name, key: key || '', run: '', when: '' }; };
add('file.docsettings', 'Document Settings…');
add('help.pen', 'Pen and tablet input');
add('script.console', 'Script Console');
add('script.run', 'Run Script…');
add('script.docs', 'Scripting Reference');
// Rust app panels (the prototype's Feel Panel is its own tuning panel).
add('help.debug', 'Debug Panel');
add('help.themedemo', 'Theme Demo');
// Scenes to look at until the drawing tools exist (brief 04).
add('help.scene.cube', 'Cube');
add('help.scene.pocket', 'Box with a Pocket');
add('help.scene.plate', 'Thin Plate');
add('help.scene.large', 'Large Scene (Timing)');
// 3. Every action needs a menu path. Two tools were only in the dock.
const walkEdit = (items, fn) => items.forEach((it, i) => { if (Array.isArray(it)) { fn(it, items, i); walkEdit(it[1], fn); } });
data.MENUBAR.forEach(([, items]) => walkEdit(items, sub => {
  if (sub[0] === 'Arc') sub[1].unshift('tool.arc');
  if (sub[0] === 'Primitives') sub[1].unshift('tool.prim');
}));
const menu = name => data.MENUBAR.find(m => m[0] === name)[1];
const file = menu('File');
file.splice(file.indexOf('file.recent'), 0, 'file.docsettings', '-');
const help = menu('Help');
help.splice(help.indexOf('help.smartdemo'), 1);
help.splice(help.indexOf('-'), 0, '-', 'help.debug', 'help.themedemo',
  ['Test Scenes', ['help.scene.cube', 'help.scene.pocket', 'help.scene.plate', 'help.scene.large']], 'help.pen');
data.MENUBAR.splice(data.MENUBAR.findIndex(m => m[0] === 'Help'), 0,
  ['Scripting', ['script.console', 'script.run', '-', 'script.docs']]);

// ---- Write Rust ----
const str = s => JSON.stringify(String(s));
const items = list => '&[' + list.map(it =>
  it === '-' ? 'Item::Separator'
  : Array.isArray(it) ? `Item::Sub(${str(it[0])}, ${items(it[1])})`
  : `Item::Action(${str(it)})`).join(', ') + ']';

let out = `// Generated by scripts/import_prototype.js from docs/prototype/Main.dc.html.
// Do not edit by hand: change the prototype or the script, and run it again.
// \`proto_run\` and \`when\` are the prototype's own fields, kept for reference;
// what actually runs in Rust is decided in \`registry.rs\`.

use super::table_types::{Item, RawAction};

pub const ACTIONS: &[RawAction] = &[
`;
for (const a of Object.values(data.ACT)) {
  out += `    RawAction { id: ${str(a.id)}, name: ${str(a.name)}, key: ${str(a.key)}, proto_run: ${str(a.run)}, when: ${str(a.when)} },\n`;
}
out += '];\n\npub const MENUBAR: &[(&str, &[Item])] = &[\n';
for (const [name, list] of data.MENUBAR) out += `    (${str(name)}, ${items(list)}),\n`;
out += '];\n\npub const DOCK: &[(&str, &[&str])] = &[\n';
for (const [name, ids] of data.DOCK) out += `    (${str(name)}, &[${ids.map(str).join(', ')}]),\n`;
out += '];\n\n/// Icon drawings: the inside of a 24 x 24 SVG, stroked, no fill.\npub const ICONS: &[(&str, &str)] = &[\n';
for (const [id, svg] of Object.entries(data.IC)) out += `    (${str(id)}, ${str(svg)}),\n`;
out += '];\n\n/// The prototype\'s list of behaviours, with whether the prototype has them.\npub const BEHAVIOURS: &[(&str, bool)] = &[\n';
for (const [name, done] of data.BEHAVIOURS) out += `    (${str(name)}, ${done ? 'true' : 'false'}),\n`;
out += '];\n';

const dest = path.join(root, 'crates/prism-app/src/actions/table.rs');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`wrote ${path.relative(root, dest)}: ${Object.keys(data.ACT).length} actions, ` +
  `${data.MENUBAR.length} menus, ${data.DOCK.length} dock groups, ${Object.keys(data.IC).length} icons`);
